"""Build working-papers.qmd from papers.json.  Run: python3 make_research.py
Abstracts in papers.json are trusted HTML (may contain <i>...</i>)."""
import json, html, pathlib

ME = "Shing-hon Lam"
root = pathlib.Path(__file__).parent
data = json.loads((root / "papers.json").read_text())

CO = data.get("coauthors", {})

def authors(a):
    a = [f"<b>{html.escape(x)}</b>" if x == ME
         else (f'<a href="{CO[x]}" target="_blank">{html.escape(x)}</a>' if x in CO else html.escape(x)) for x in a]
    return a[0] if len(a) == 1 else ", ".join(a[:-1]) + " and " + a[-1]

out = ['---', 'title: "Working Papers"', 'aliases:', '  - /research.html', '  - /research/', 'toc: false', '---', '',
       '<!-- Generated by make_research.py from papers.json. Edit papers.json, not this file. -->', '']
n = 0
for sec in data["sections"]:
    out.append(f'## {sec["title"]}\n')
    out.append('<div class="pub-list">')
    for p in sec["papers"]:
        n += 1
        pid = f"p{n}"
        status = f' <span class="pub-status">{html.escape(p["status"])}</span>' if p.get("status") else ""
        out.append('<div class="pub-entry">')
        out.append(f'<div class="pub-title">{html.escape(p["title"])}</div>')
        out.append(f'<div class="pub-authors">{authors(p["authors"])}{status}</div>')
        btns = []
        if p.get("abstract"):
            btns.append(f'<button class="btn-pill btn-outline" data-toggle-target="abs-{pid}">Abstract</button>')
        if p.get("presented"):
            btns.append(f'<button class="btn-pill btn-outline" data-toggle-target="pres-{pid}">Presented at</button>')
        for label, url in p.get("links", {}).items():
            cls = "btn-ssrn" if label.upper() == "SSRN" else "btn-solid"
            btns.append(f'<a class="btn-pill {cls}" href="{html.escape(url)}" target="_blank">{html.escape(label)}</a>')
        out.append(f'<div class="pub-actions">{"".join(btns)}</div>')
        if p.get("abstract"):
            out.append(f'<div class="pub-collapse" id="abs-{pid}"><p>{p["abstract"]}</p></div>')
        if p.get("presented"):
            items = "".join(f"<li>{html.escape(x)}</li>" for x in p["presented"])
            out.append(f'<div class="pub-collapse" id="pres-{pid}"><ul>{items}</ul></div>')
        out.append('</div>')
    out.append('</div>\n')

out.append('''```{=html}
<script>
document.addEventListener("click", function (e) {
  var b = e.target.closest("[data-toggle-target]");
  if (!b) return;
  var t = document.getElementById(b.getAttribute("data-toggle-target"));
  if (!t) return;
  var open = t.classList.toggle("show");
  b.classList.toggle("active", open);
  b.setAttribute("aria-expanded", open);
});
</script>
```''')
(root / "working-papers.qmd").write_text("\n".join(out) + "\n")
print(f"working-papers.qmd: {n} papers")
